r"""icons_to_vectors: turn MedicAll's icon SVGs into the vector drawables the Compose theme loads (SPEC:R117).

    python tools/icons_to_vectors.py --phosphor <dir of Phosphor regular SVGs> --custom docs/design/icons \
        --out ui/src/commonMain/composeResources/drawable

Phosphor's regular icons (https://github.com/phosphor-icons/core, assets/regular, MIT) are one filled path on a
256 grid; each becomes ph_<name>.xml. The custom set in docs/design/icons is stroked at 1.5 on a 24 grid with
round caps and joins, from circles, ellipses, rounded rects and paths, some inside rotated or moved groups; each
becomes mc_<name>.xml. Vector drawables draw no dashes, so a dashed circle (dose missed) is cut into its dashes,
measured as the SVG measures them (pathLength and stroke-dasharray). Every drawable is drawn in opaque black,
which Compose's Icon replaces with the colour it is given: the colour lives in the theme, not here (SPEC:R93).

Standard library only.
"""
import argparse
import math
import os
import re
import sys
import xml.etree.ElementTree as ET

SVG = "{http://www.w3.org/2000/svg}"
INK = "#FF000000"
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/icons_to_vectors.py from {source}; do not edit by hand. -->\n')


def num(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def circle_path(cx, cy, r):
    return "M%s,%sA%s,%s 0,1 1,%s,%sA%s,%s 0,1 1,%s,%sZ" % (
        num(cx + r), num(cy), num(r), num(r), num(cx - r), num(cy), num(r), num(r), num(cx + r), num(cy))


def ellipse_path(cx, cy, rx, ry):
    return "M%s,%sA%s,%s 0,1 1,%s,%sA%s,%s 0,1 1,%s,%sZ" % (
        num(cx + rx), num(cy), num(rx), num(ry), num(cx - rx), num(cy), num(rx), num(ry), num(cx + rx), num(cy))


def rect_path(x, y, w, h, rx, ry):
    if rx <= 0 and ry <= 0:
        return "M%s,%sH%sV%sH%sZ" % (num(x), num(y), num(x + w), num(y + h), num(x))
    rx = min(rx or ry, w / 2)
    ry = min(ry or rx, h / 2)
    a = lambda ex, ey: "A%s,%s 0,0 1,%s,%s" % (num(rx), num(ry), num(ex), num(ey))
    return ("M%s,%sH%s" % (num(x + rx), num(y), num(x + w - rx)) + a(x + w, y + ry) +
            "V%s" % num(y + h - ry) + a(x + w - rx, y + h) +
            "H%s" % num(x + rx) + a(x, y + h - ry) +
            "V%s" % num(y + ry) + a(x + rx, y) + "Z")


def dashed_circle(cx, cy, r, path_length, dasharray):
    """The dashes of a circle drawn from (cx + r, cy) clockwise, as SVG starts and runs a circle's stroke."""
    dash, gap = dasharray
    period = dash + gap
    count = int(round(path_length / period))
    if abs(count * period - path_length) > 1e-6:
        raise ValueError("a dashed circle must hold a whole number of dashes")
    parts = []
    for i in range(count):
        a0 = 2 * math.pi * (i * period) / path_length
        a1 = 2 * math.pi * (i * period + dash) / path_length
        parts.append("M%s,%sA%s,%s 0,0 1,%s,%s" % (
            num(cx + r * math.cos(a0)), num(cy + r * math.sin(a0)), num(r), num(r),
            num(cx + r * math.cos(a1)), num(cy + r * math.sin(a1))))
    return "".join(parts)


def f(el, name, default=0.0):
    v = el.get(name)
    return float(v) if v is not None else default


def shape_path(el):
    tag = el.tag.replace(SVG, "")
    if tag == "path":
        return el.get("d")
    if tag == "circle":
        cx, cy, r = f(el, "cx"), f(el, "cy"), f(el, "r")
        if el.get("stroke-dasharray"):
            dashes = [float(v) for v in re.split(r"[\s,]+", el.get("stroke-dasharray").strip())]
            if len(dashes) != 2:
                raise ValueError("only a dash and a gap are supported")
            length = f(el, "pathLength", 2 * math.pi * r)
            return dashed_circle(cx, cy, r, length, dashes)
        return circle_path(cx, cy, r)
    if tag == "ellipse":
        return ellipse_path(f(el, "cx"), f(el, "cy"), f(el, "rx"), f(el, "ry"))
    if tag == "rect":
        return rect_path(f(el, "x"), f(el, "y"), f(el, "width"), f(el, "height"), f(el, "rx"), f(el, "ry"))
    raise ValueError("unsupported element <%s>" % tag)


def group_attrs(transform):
    """A vector <group>'s attributes for an SVG transform: rotate(a cx cy), or translate(x y) then rotate(a)."""
    if not transform:
        return ""
    ops = re.findall(r"(\w+)\(([^)]*)\)", transform)
    attrs = {}
    for name, args in ops:
        vals = [float(v) for v in re.split(r"[\s,]+", args.strip())]
        if name == "translate":
            if "rotation" in attrs:
                raise ValueError("a translate after a rotate is not supported")
            attrs["translateX"], attrs["translateY"] = vals[0], (vals[1] if len(vals) > 1 else 0.0)
        elif name == "rotate":
            attrs["rotation"] = vals[0]
            if len(vals) == 3:
                if "translateX" in attrs:
                    raise ValueError("a translate before a centred rotate is not supported")
                attrs["pivotX"], attrs["pivotY"] = vals[1], vals[2]
        else:
            raise ValueError("unsupported transform %s" % name)
    return "".join(' android:%s="%s"' % (k, num(v)) for k, v in attrs.items())


def custom_body(node, style, indent):
    out = []
    for el in node:
        tag = el.tag.replace(SVG, "")
        if tag in ("title", "desc"):
            continue
        if tag == "g":
            s = dict(style)
            for k in ("stroke-width", "stroke-linecap", "stroke-linejoin"):
                if el.get(k):
                    s[k] = el.get(k)
            attrs = group_attrs(el.get("transform"))
            if attrs:
                inner = custom_body(el, s, indent + "    ")
                out.append("%s<group%s>\n%s%s</group>\n" % (indent, attrs, inner, indent))
            else:
                out.append(custom_body(el, s, indent))
            continue
        if el.get("transform"):
            raise ValueError("a transform on a shape is not supported")
        out.append('%s<path\n%s    android:pathData="%s"\n%s    android:strokeColor="%s"\n'
                   '%s    android:strokeWidth="%s"\n%s    android:strokeLineCap="%s"\n'
                   '%s    android:strokeLineJoin="%s" />\n' % (
                       indent, indent, shape_path(el), indent, INK, indent, style["stroke-width"],
                       indent, style["stroke-linecap"], indent, style["stroke-linejoin"]))
    return "".join(out)


def vector(source, viewport, body):
    return (HEADER.format(source=source) +
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n'
            '    android:viewportWidth="%s"\n    android:viewportHeight="%s">\n%s</vector>\n'
            % (viewport, viewport, body))


def resource_name(prefix, filename):
    return prefix + re.sub(r"[^a-z0-9]", "_", os.path.splitext(filename)[0].lower())


def phosphor(path):
    root = ET.parse(path).getroot()
    if root.get("viewBox") != "0 0 256 256":
        raise ValueError("%s: not a Phosphor 256 grid" % path)
    paths = [el for el in root.iter() if el.tag == SVG + "path"]
    others = [el for el in root.iter() if el.tag.replace(SVG, "") not in ("svg", "path", "title")]
    if not paths or others:
        raise ValueError("%s: expected filled paths only" % path)
    body = "".join('    <path\n        android:fillColor="%s"\n        android:pathData="%s" />\n'
                   % (INK, p.get("d")) for p in paths)
    return vector("Phosphor regular " + os.path.basename(path) + " (MIT)", 256, body)


def custom(path):
    root = ET.parse(path).getroot()
    if root.get("viewBox") != "0 0 24 24":
        raise ValueError("%s: not a 24 grid" % path)
    style = {"stroke-width": "1.5", "stroke-linecap": "round", "stroke-linejoin": "round"}
    body = custom_body(root, style, "    ")
    return vector("docs/design/icons/" + os.path.basename(path), 24, body)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--phosphor", required=True)
    ap.add_argument("--custom", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    written = 0
    for folder, prefix, convert in ((args.phosphor, "ph_", phosphor), (args.custom, "mc_", custom)):
        for name in sorted(os.listdir(folder)):
            if not name.endswith(".svg"):
                continue
            xml = convert(os.path.join(folder, name))
            with open(os.path.join(args.out, resource_name(prefix, name) + ".xml"), "w", encoding="utf-8",
                      newline="\n") as out:
                out.write(xml)
            written += 1
    print("wrote %d vector drawables to %s" % (written, args.out))


if __name__ == "__main__":
    sys.exit(main())
